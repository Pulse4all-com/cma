/**
 * The metric catalog's generator: reads docs/metrics/catalog.json and writes
 *   - docs/metrics/METRICS.md           the readable document, grouped by surface → page → figure
 *   - web/src/lib/metrics-catalog.json  the verbatim copy the Metrics page bundles (the Docker
 *                                       build's context is web/, so the page cannot read docs/)
 * Both are generated, never edited by hand; web/verify/metrics.mjs fails when either is stale.
 * Deterministic on purpose (no clock, no environment): the same catalog.json always gives the same
 * bytes, so "regenerates byte-identical" is checkable.
 *
 *   node scripts/metrics-doc.mjs           writes both files
 *   node scripts/metrics-doc.mjs --check   writes nothing, exits 1 when either file is stale
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = fileURLToPath(new URL(".", import.meta.url));
export const CATALOG_PATH = new URL("../../docs/metrics/catalog.json", `file://${here}`).pathname;
export const DOC_PATH = new URL("../../docs/metrics/METRICS.md", `file://${here}`).pathname;
export const COPY_PATH = new URL("../src/lib/metrics-catalog.json", `file://${here}`).pathname;

const SURFACES = ["welcome", "live", "dashboard", "report", "configuration", "agent", "export", "api"];
const SURFACE_TITLES = {
  welcome: "Welcome",
  live: "Live board",
  dashboard: "Dashboard",
  report: "Reports",
  configuration: "Configuration",
  agent: "The person's own pages",
  export: "Downloaded files",
  api: "Returned with the data, not shown on a page",
};

/** A cell of a Markdown table: pipes escaped, line breaks flattened */
const cell = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ");

/** The verbatim copy for the web build: the catalog's entries under the copy's own _about line */
export function webCopy(raw) {
  const catalog = JSON.parse(raw);
  return `${JSON.stringify(
    {
      _about:
        "Generated by web/scripts/metrics-doc.mjs from docs/metrics/catalog.json, so the Docker build (context web/) can bundle the catalog into the Metrics page. Never edited by hand; verify:metrics fails when it differs from docs/metrics/catalog.json.",
      entries: catalog.entries,
    },
    null,
    2,
  )}\n`;
}

function entrySection(e) {
  const lines = [];
  lines.push(`### \`${e.key}\``);
  lines.push("");
  const where = e.tile ? `**${e.tile}** on ${e.page}` : `${e.page}, returned with the data and not shown on a page`;
  lines.push(`${where} · ${e.title.en}${e.title.nl ? ` (${e.title.nl})` : ""}`);
  lines.push("");
  lines.push(e.definition);
  lines.push("");
  lines.push("**Formula as computed**");
  lines.push("");
  lines.push("```");
  lines.push(e.formula.trimEnd());
  lines.push("```");
  lines.push("");
  lines.push(`**Unit** ${e.unit} · **Grain** ${e.grain.join(", ")} · **Status** ${e.status.join(", ")}`);
  lines.push("");
  lines.push("**Sources**");
  lines.push("");
  lines.push("| Table | Columns | Owner | Fed by | Cadence |");
  lines.push("|---|---|---|---|---|");
  for (const s of e.sources) {
    lines.push(`| \`${s.table}\` | ${cell(s.columns.join(", "))} | ${s.owner} | ${cell(s.fed_by)} | ${cell(s.cadence)} |`);
  }
  lines.push("");
  lines.push("**Filters**");
  lines.push("");
  for (const f of e.filters) lines.push(`- ${f}`);
  lines.push("");
  lines.push(`**Time** ${e.time}`);
  if (e.comparison) {
    lines.push("");
    lines.push(`**Previous period** ${e.comparison}`);
  }
  if (e.settings.length > 0) {
    lines.push("");
    lines.push("**Settings**");
    lines.push("");
    lines.push("| Setting | Default | Pulse4all |");
    lines.push("|---|---|---|");
    for (const s of e.settings) lines.push(`| \`${s.key}\` | ${cell(s.default)} | ${cell(s.pulse4all)} |`);
  }
  lines.push("");
  const per = e.permissions.perPerson ? `, and \`${e.permissions.perPerson}\` in the tenant setting \`reports.per_person\`` : "";
  lines.push(`**Who may see it** ${e.permissions.anyOf.map((p) => `\`${p}\``).join(" or ")}${per}`);
  lines.push("");
  lines.push(`**Refresh** ${e.refresh}`);
  lines.push("");
  const sql = e.computed_in.sql.map((s) => `\`${s.object}\` (${s.migration})`);
  const ts = e.computed_in.ts.map((x) => `\`${x.export}\` in ${x.file}`);
  lines.push(`**Computed in** ${[...sql, ...ts].join("; ") || "—"}`);
  lines.push("");
  if (e.verify_sql) {
    lines.push("**Verification query** (Studio, with the tenant id and the period's business dates filled in)");
    lines.push("");
    lines.push("```sql");
    lines.push(e.verify_sql.trimEnd());
    lines.push("```");
  } else {
    lines.push("**Verification query** none is faithful for this figure; the notes name the closest check");
  }
  lines.push("");
  lines.push(`**Fixture check** ${e.fixture_check}`);
  if (e.prerequisites.length > 0) {
    lines.push("");
    lines.push("**Data prerequisites**");
    lines.push("");
    for (const p of e.prerequisites) {
      lines.push(`- ${p.item}${p.check ? ` (data quality check \`${p.check}\`)` : ""}`);
    }
  }
  lines.push("");
  lines.push(`**Documented in** ${e.docs.join("; ") || "—"}`);
  if (e.notes) {
    lines.push("");
    lines.push("**Notes**");
    lines.push("");
    lines.push(e.notes);
  }
  lines.push("");
  return lines.join("\n");
}

/** The whole document from the catalog's raw JSON text */
export function generate(raw) {
  const catalog = JSON.parse(raw);
  const out = [];
  out.push("# CMA metric catalog");
  out.push("");
  out.push(
    "Generated from [catalog.json](catalog.json) by `web/scripts/metrics-doc.mjs`; never edited by hand " +
      "(`verify:metrics` fails when this file is stale). One section per figure the Workspace shows, grouped by " +
      "surface, page and figure: the definition, the formula as the code computes it, the sources with their " +
      "cadence, the time rules, the settings, who may see it, an independent verification query and the audit " +
      "status. The audit's findings are in [AUDIT-2026-10-23.md](AUDIT-2026-10-23.md); the catalog is shown on " +
      "Configuration → Metrics.",
  );
  out.push("");
  const entries = catalog.entries;
  out.push(`${entries.length} figures. Statuses: ${
    ["verified", "discrepancy", "ambiguous", "prerequisite_missing", "cadence_unconfirmed"]
      .map((s) => `${s} ${entries.filter((e) => e.status.includes(s)).length}`)
      .join(" · ")
  }.`);
  out.push("");
  for (const surface of SURFACES) {
    const ofSurface = entries.filter((e) => e.surface === surface);
    if (ofSurface.length === 0) continue;
    out.push(`## ${SURFACE_TITLES[surface]}`);
    out.push("");
    const pages = [...new Set(ofSurface.map((e) => e.page))];
    for (const page of pages) {
      out.push(`### ${page}`);
      out.push("");
      for (const e of ofSurface.filter((x) => x.page === page)) out.push(entrySection(e).replace(/^### /, "#### "));
    }
  }
  return `${out.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd()}\n`;
}

if (process.argv[1]?.endsWith("metrics-doc.mjs")) {
  const raw = readFileSync(CATALOG_PATH, "utf8");
  const doc = generate(raw);
  const copy = webCopy(raw);
  if (process.argv.includes("--check")) {
    const staleDoc = readFileSync(DOC_PATH, "utf8") !== doc;
    const staleCopy = readFileSync(COPY_PATH, "utf8") !== copy;
    if (staleDoc || staleCopy) {
      console.error(`metrics-doc: stale${staleDoc ? " METRICS.md" : ""}${staleCopy ? " metrics-catalog.json" : ""}; run node scripts/metrics-doc.mjs`);
      process.exit(1);
    }
    console.log("metrics-doc: up to date");
  } else {
    writeFileSync(DOC_PATH, doc);
    writeFileSync(COPY_PATH, copy);
    console.log(`metrics-doc: wrote METRICS.md (${doc.length} bytes) and src/lib/metrics-catalog.json`);
  }
}
